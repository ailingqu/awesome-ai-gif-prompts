const slug = (s) => s.toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, '').trim().replace(/\s+/g, '-');

async function build(lang) {
  const t = T[lang];
  const out = [];
  out.push(`# Awesome AI GIF Prompts`, '', t.switch, '');
  out.push(
    `![prompts](https://img.shields.io/badge/prompts-${data.prompts.length}-ff713a) ![model](https://img.shields.io/badge/model-GPT%20Image%202.6-8a63d2) ![license](https://img.shields.io/badge/license-CC%20BY%204.0-2bb3a3) [![awesome](https://awesome.re/badge.svg)](https://awesome.re)`,
    '',
  );
  out.push(t.tagline, '', `> ${t.try}`, '');

  // 封面：每个分类取第一个已生成的示例，拼成一行
  const cover = [];
  for (const c of data.categories) {
    for (const p of data.prompts.filter((x) => x.category === c.id)) {
      if (await exists(path.join(root, 'gifs', `${p.id}.gif`))) { cover.push(p); break; }
    }
  }
  if (cover.length) {
    out.push('<p align="center">');
    for (const p of cover) out.push(`  <img src="gifs/${p.id}.gif" alt="${t.itemTitle(p)}" height="150">`);
    out.push('</p>', '');
  }

  out.push(`## ${t.toc}`, '');
  out.push(`- [${t.how}](#${slug(t.how)})`);
  for (const c of data.categories) {
    const n = data.prompts.filter((p) => p.category === c.id).length;
    out.push(`- [${t.catTitle(c)}](#${slug(t.catTitle(c))}) · ${t.count(n)}`);
  }
  out.push(`- [${t.api}](#${slug(t.api)})`, '');

  out.push(`## ${t.how}`, '', t.howBody[0], '', t.howBody[1], '', '```text', data.loopSuffix, '```', '');
  out.push(`### ${t.formula}`, '', t.formulaBody, '');
  out.push(`### ${t.tips}`, '', ...t.tipsList.map((s) => `- ${s}`), '');

  let n = 0;
  for (const c of data.categories) {
    out.push(`## ${t.catTitle(c)}`, '');
    for (const p of data.prompts.filter((x) => x.category === c.id)) {
      n += 1;
      out.push(`### ${n}. ${t.itemTitle(p)}`, '');
      const r = results[p.id];
      if (r && (await exists(path.join(root, 'gifs', `${p.id}.gif`)))) {
        out.push(`<img src="gifs/${p.id}.gif" alt="${t.itemTitle(p)}" width="360">`, '');
        const meta = [`${r.frames} ${t.frames}`, `${r.width}×${r.height}`, `${(r.durationMs / 1000).toFixed(1)}s`, r.model];
        if (r.generatedAt) meta.push(`${t.generated} ${r.generatedAt}`);
        out.push(`<sub>${meta.join(' · ')}</sub>`, '');
      } else {
        out.push(t.pending, '');
      }
      out.push(`**${t.prompt}**`, '', '```text', p.prompt, '```', '');
      if (p.tips && lang === 'en') out.push(`> 💡 **${t.tip}:** ${p.tips}`, '');
      if (p.tips_zh && lang === 'zh') out.push(`> 💡 **${t.tip}：** ${p.tips_zh}`, '');
      if (p.tags?.length) out.push(p.tags.map((x) => `\`${x}\``).join(' '), '');
    }
  }

  out.push(`## ${t.api}`, '', t.apiBody, '');
  out.push(
    '```bash',
    'curl https://apiany.ai/v1/images/generations/sync \\',
    '  -H "Authorization: Bearer $APIANY_API_KEY" \\',
    '  -H "Content-Type: application/json" \\',
    `  -d '{"model": "gpt-image-2.6", "output_format": "gif", "prompt": "A cheerful cartoon cat waving hello. ${data.loopSuffix}"}'`,
    '```',
    '',
    t.script,
    '',
    '```bash',
    `git clone https://github.com/ailingqu/${REPO}.git && cd ${REPO}`,
    'cp .env.example .env   # fill in APIANY_API_KEY',
    'npm run generate        # only generates prompts without a GIF',
    'npm run build           # rebuilds README.md and README_zh.md',
    '```',
    '',
  );
  out.push(`## ${t.source}`, '', t.sourceBody, '');
  out.push(`## ${t.contrib}`, '', t.contribBody, '');
  out.push(`## ${t.license}`, '', t.licenseBody, '');
  await writeFile(path.join(root, t.file), out.join('\n'));
  console.log(`wrote ${t.file}`);
}

await build('en');
await build('zh');
